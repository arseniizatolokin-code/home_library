/// Замикання: фабрика предикатів і лічильник.
library;

import 'book_parser.dart';

/// Створює предикат «книга має щонайменше [minPages] сторінок».
///
/// Повернена функція захоплює параметр [minPages] і зберігає його,
/// поки на неї є посилання.
bool Function(Book book) longerThan(int minPages) =>
    (book) => book.pages >= minPages;

/// Створює лічильник: кожен виклик повертає наступне число, починаючи з 1.
///
/// Повернена функція захоплює локальну змінну `count`, яка живе,
/// поки живе сама функція, і не залежить від інших лічильників.
int Function() createCounter() {
  var count = 0;
  return () => ++count;
}
